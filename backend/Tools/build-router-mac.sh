#!/bin/bash
# Build an owner-run development bundle without starting/stopping a router.
set -euo pipefail
root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
mode=${1:---release}
destination=${2:-"$root/backend/target/dev-app/Listen Router.app"}
case "$mode" in
  --debug) cargo build --manifest-path "$root/backend/Cargo.toml" -p listen-router-app; profile=debug ;;
  --release) cargo build --manifest-path "$root/backend/Cargo.toml" -p listen-router-app --release; profile=release ;;
  *) printf 'Usage: %s [--debug|--release] [output.app]\n' "$0" >&2; exit 2 ;;
esac
parent=$(dirname -- "$destination")
mkdir -p "$parent"
stage=$(mktemp -d "$parent/.router-build.XXXXXX")
bundle="$stage/Listen Router.app"
mkdir -p "$bundle/Contents/MacOS" "$bundle/Contents/Resources"
cp "$root/backend/target/$profile/listen-router-app" "$bundle/Contents/MacOS/ListenRouter"
# The artwork hash changes its resource name so Launch Services does not retain
# an older icon for development builds with the same bundle version.
icon_hash=$(shasum -a 256 "$root/backend/crates/router-app/icons/icon.icns" | cut -c 1-12)
icon_name="Router-$icon_hash.icns"
cp "$root/backend/crates/router-app/icons/icon.icns" "$bundle/Contents/Resources/$icon_name"
cp "$root/LICENSE" "$bundle/Contents/Resources/LICENSE"
cp "$root/NOTICE" "$bundle/Contents/Resources/NOTICE"
cp "$root/THIRD_PARTY.md" "$bundle/Contents/Resources/THIRD_PARTY.md"
cat > "$bundle/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
<key>CFBundleIdentifier</key><string>app.listen.router</string>
<key>CFBundleName</key><string>Listen Router</string>
<key>CFBundleDisplayName</key><string>Listen Router</string>
<key>CFBundleExecutable</key><string>ListenRouter</string>
<key>CFBundlePackageType</key><string>APPL</string>
<key>CFBundleShortVersionString</key><string>0.1.0</string>
<key>CFBundleVersion</key><string>1</string>
<key>CFBundleIconFile</key><string>$icon_name</string>
<key>NSHighResolutionCapable</key><true/>
<key>NSLocalNetworkUsageDescription</key><string>Connect your own Listen devices to this router.</string>
</dict></plist>
PLIST
printf 'Generated Listen Router development bundle\n' > "$bundle/Contents/Resources/ListenDevelopmentBuild.txt"
codesign --force --sign - "$bundle"
codesign --verify --strict "$bundle"
if [ -e "$destination" ]; then
  if [ ! -f "$destination/Contents/Resources/ListenDevelopmentBuild.txt" ]; then
    printf 'Existing output was not generated by this tool; preserved: %s\n' "$destination" >&2
    exit 1
  fi
  mv "$destination" "$destination.previous.$(date +%Y%m%d%H%M%S)"
fi
mv "$bundle" "$destination"
rmdir "$stage"
printf 'Built development bundle: %s\nAd-hoc signed; not notarized or published.\n' "$destination"
